#!/usr/bin/env python3
"""Run from repo root: python tools/gen_docs.py
Reads tools/requirements.py. Writes generated docs. Safe to re-run."""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from requirements import REQS, PHASES, CUTLINES, DEADLINE, PROJECT

ROOT = pathlib.Path(__file__).resolve().parent.parent
D = ROOT / "docs"


def phase_ids():
    return [p["id"] for p in PHASES]


def req_ids():
    return [r[0] for r in REQS]


def check_consistency():
    ids = set(req_ids())
    assert len(ids) == len(REQS), "duplicate requirement id"
    covered = set()
    for p in PHASES:
        for rid in p["covers"].split():
            assert rid in ids, f"{p['id']} covers unknown id {rid}"
            covered.add(rid)
    missing = ids - covered
    assert not missing, f"requirements with no phase: {sorted(missing)}"


def checklist():
    out = ["# SPEC_CHECKLIST", "",
           "Generated by tools/gen_docs.py. Agents may edit ONLY the Status and Evidence columns. Never edit requirement text (change tools/requirements.py instead).",
           "Status values: TODO / IN PROGRESS / DONE / SPEC GAP. A row without Evidence is not DONE.", "",
           "| ID | Requirement | Phase | How to verify | Status | Evidence |", "|---|---|---|---|---|---|"]
    for rid, g, text, ph, how in REQS:
        out.append(f"| {rid} | {text} | {ph} | {how} | TODO | |")
    (D / "SPEC_CHECKLIST.md").write_text("\n".join(out) + "\n", encoding="utf-8")


def req_table():
    out = ["| ID | Group | Requirement | Phase | Verified by |", "|---|---|---|---|---|"]
    for rid, g, text, ph, how in REQS:
        out.append(f"| {rid} | {g} | {text} | {ph} | {how} |")
    block = "\n".join(out)
    prd = D / "prd.md"
    s = prd.read_text(encoding="utf-8")
    new = re.sub(r"<!-- REQ_TABLE_START -->.*<!-- REQ_TABLE_END -->",
                 "<!-- REQ_TABLE_START -->\n" + block + "\n<!-- REQ_TABLE_END -->", s, flags=re.S)
    prd.write_text(new, encoding="utf-8")


def phases_md():
    tot = sum(p["hours"] for p in PHASES)
    out = ["# phases.md", "",
           f"Deadline: **{DEADLINE}**. Total planned build time: **{tot} h**. Generated by tools/gen_docs.py.", "",
           "## Clock rules (hard)",
           "- Feature freeze: **Fri 27 Nov 06:00**. After this only bug fixes, claims audit, deploy.",
           "- Final deploy + logged-out test: **Fri 27 Nov 09:00**. Form submission: **by 10:30**, never at 11:59.",
           "- Minimum submit-worthy = CUT LINE 2 (P7 done). If behind at Thu 22:00, stop starting new scenes.",
           "- Cutting a scene makes SRC-07/SRC-08..11 partial: log `SPEC GAP` in progress.md, never cut silently.", "",
           "## Definition of Done (every phase)",
           "1. All acceptance boxes ticked with raw output or screenshot paths.",
           "2. `npm run lint && npm run typecheck && npm run test && npm run build` pass, output pasted.",
           "3. progress.md and SPEC_CHECKLIST.md updated (Status + Evidence).",
           "4. Small conventional commits pushed to main; phase tagged `phase-Pn`.", ""]
    for p in PHASES:
        out += [f"## {p['id']} {p['title']} ({p['hours']} h)"]
        if p["id"] in CUTLINES:
            out.append(f"**{CUTLINES[p['id']]}**")
        out += [f"- Depends on: {p['depends']}", f"- Goal: {p['goal']}", f"- Requirement IDs: {p['covers']}", "- Slices (one agent prompt each):"]
        out += [f"  - {s}" for s in p["slices"]]
        out += ["- Acceptance:"] + [f"  - [ ] {a}" for a in p["accept"]]
        out += ["- Report must include: raw command output, test names, screenshot paths, git commit hash.", ""]
    (D / "phases.md").write_text("\n".join(out), encoding="utf-8")
    m = ["flowchart TD"]
    for p in PHASES:
        label = f"{p['id']} {p['title']}".replace("(", "[").replace(")", "]")
        m.append(f'  {p["id"]}["{label}"]')
    for p in PHASES:
        if p["depends"] != "none":
            m.append(f'  {p["depends"]} --> {p["id"]}')
    for pid in CUTLINES:
        m.append(f"  style {pid} stroke-width:3px")
    (D / "phases.mmd").write_text("\n".join(m) + "\n", encoding="utf-8")


def docs_map():
    out = []
    for f in sorted(D.glob("*.md")):
        if f.name.startswith("_") or f.name == "DEEPSEEK_BRIEF.md":
            continue
        heads = [h.strip("# ").strip() for h in f.read_text(encoding="utf-8").splitlines() if h.startswith("## ")]
        out.append(f"- docs/{f.name}: " + "; ".join(heads[:14]))
    return "\n".join(out)


def brief():
    agents = (ROOT / "AGENTS.md").read_text(encoding="utf-8")
    comp = ["## Phases (compact)"]
    for p in PHASES:
        tag = f" [{CUTLINES[p['id']]}]" if p["id"] in CUTLINES else ""
        comp.append(f"### {p['id']} {p['title']} ({p['hours']} h){tag}\nGoal: {p['goal']}\nIDs: {p['covers']}\nSlices: " + " | ".join(p["slices"]) + "\nAccept: " + " | ".join(p["accept"]))
    ids = ["## Requirement IDs (short)"] + [f"{r[0]}: {r[2][:90]} [{r[3]}]" for r in REQS]
    text = f"""# DEEPSEEK_BRIEF ({PROJECT})
Generated by tools/gen_docs.py. Lean context for DeepSeek. Antigravity reads the full docs from the repo.

## Project summary
- The Regret Machine: browser game for Intel 1 Million Minds (CMRIT x Intel), Round 1. Gen Z walk-in shoppers pick a shiny unbranded laptop, then live 3 years in about 2.5 minutes through 4 playable scenes (lecture, long day, creator night, private files). Each scene ends in a split reveal: the decayed shelf laptop vs an Intel Core Ultra Series 3 AI PC. Ends with a Receipt, a Fair Fight comparison, a personalised recommendation, share card and store-staff screen.
- Deadline: {DEADLINE}
- Stack: Vite + TypeScript (vanilla, no framework), CSS tokens, Vitest, Playwright, GitHub Pages. No backend, no database, no secrets, no analytics.
- Windows 11, projects in E:\\Projects\\{PROJECT}. Team of 3. Coding agent: Antigravity (fast Gemini Flash-class model).
- Design identity: "Sale Tag Decay" (flyer look that ages as --decay rises). Full spec in docs/design.md.

## Setup facts (fill before first prompt)
- Node major: 24 (run `node -v`). Repo URL: https://github.com/manishchandraraturi/regret-machine.git . Remote created: yes. First commit pushed: yes.

{agents}

{chr(10).join(comp)}

{chr(10).join(ids)}

## Docs map (cite file + section in prompts)
{docs_map()}
"""
    (D / "DEEPSEEK_BRIEF.md").write_text(text, encoding="utf-8")
    return len(text)


if __name__ == "__main__":
    check_consistency()
    checklist(); req_table(); phases_md(); n = brief()
    print(f"OK. {len(REQS)} requirements, {len(PHASES)} phases. DEEPSEEK_BRIEF chars={n} approx_tokens={n//4}")
